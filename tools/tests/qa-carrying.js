// Real Orchard actions: pickup/drop/deliver, carried Cub, free throw and restart.
const assert = (ok, message) => { if (!ok) throw new Error(message) }
run(30); play('cub')
const { mama, cub } = S.stage
const tree = S.stage.swipes.targets.find(t => t.id === 'acorn-tree')
walkTo(cub, tree.position().x, tree.position().z, 900, 0.3); run(30)
assert(jumpSwipe() >= 0, 'tree acorn should be reachable on a coached jump')
run(180)
const pick = () => S.stage.interactions.list.find(i => i.id === 'pick-tree-cub')
assert(pick()?.enabled(), 'knocked acorn should settle and become collectible')
tap('KeyE'); run(30)
assert(!pick().enabled() && st().obj.includes('Bring'), 'B should pick up the acorn')
await shot('qa2-acorn-held')
tap('KeyE'); run(180)
assert(pick().enabled(), 'B should put it down and allow another pickup')
const at = pick().anchor(); walkTo(cub, at.x, at.z, 240, 0.3); tap('KeyE'); run(30)
assert(!pick().enabled(), 'dropped acorn should be retrievable')
play('mama'); mama.placeAt(V(cub.position.x + 1.5, cub.feetY, cub.position.z)); run(30); tap('KeyE'); run(30)
assert(S.stage.coop.carrying, 'Mama should carry Cub while Cub holds an acorn')
assert(st().obj.includes('Bring'), 'carried Cub should keep the acorn')
await shot('qa2-acorn-back')
tap('KeyR'); run(120)
assert(cub.mode === 'walk' && !S.stage.coop.carrying && st().obj.includes('Bring'), 'thrown Cub should land with her acorn')
await shot('qa2-acorn-thrown-landed')
play('cub'); walkTo(cub, 2.2, 14.4, 900, 0.4); run(30)
assert(prompts().includes('Put in!'), 'basket should offer delivery')
tap('KeyE'); run(30)
assert(st().obj.includes('(1/3)'), 'delivery should count exactly once')
tap('KeyE'); run(30)
assert(st().obj.includes('(1/3)'), 'repeated B should not duplicate delivery')
// Mama also picks up an acorn. Jumping off the hay keeps it held.
mama.placeAt(V(-16.6, 3.2, 15)); cub.placeAt(V(0, 0, 25)); run(30); play('mama'); tap('KeyE'); run(30)
assert(st().obj.includes('Bring'), 'Mama should be able to pick up the hay acorn')
hopTo(mama, -13, 15); run(90)
assert(st().obj.includes('Bring'), 'falling off a ledge should keep the acorn')
walkTo(mama, 2.2, 14.4, 900, 0.4); run(30); tap('KeyE'); run(30)
assert(st().obj.includes('(2/3)'), 'Mama should deliver the second acorn')
// Restart via the real pause menu must reset delivered and held items.
play('cub'); cub.placeAt(V(19.5, 4.2, 12)); run(30); tap('KeyE'); run(30)
assert(st().obj.includes('Bring'), 'hold the last acorn before restarting')
play('mama'); mama.placeAt(V(21, 4.2, 12)); run(30); tap('KeyE'); run(30)
assert(S.stage.coop.carrying, 'restart fixture should carry both Cub and the last acorn')
tap('Escape'); tap('KeyS'); tap('KeyS'); tap('KeyS'); tap('Space'); run(30)
assert(st().obj.includes('(0/3)'), 'restart should reset the basket count')
assert(!S.stage.coop.carrying && S.stage.cub.mode === 'walk', 'restart should clear the previous carry state')
assert(S.stage.interactions.list.find(i => i.id === 'pick-hay-cub').enabled(), 'restart should restore the hay acorn')
assert(S.stage.swipes.targets.find(t => t.id === 'acorn-tree').enabled(), 'restart should restore the hanging acorn')
// Orchard has no water. Exercise the real carry system in Night's water as a fixture.
S.loadLevel(5); run(30)
const { Carrying } = await import('/src/game/carry.ts')
const { Group } = await import('/node_modules/.vite/deps/three.js')
const stage = S.stage
const carrying = new Carrying(stage.interactions, [stage.mama, stage.cub], stage.terrain, stage.particles, () => {}, S.physics.RAPIER, stage.world)
const item = carrying.add('water-test', new Group(), V(0, 0.3, 19))
const step = (frames, codes = []) => { for (let i = 0; i < frames; i++) { run(1, codes); carrying.update(1 / 60) } }
play('cub'); stage.cub.placeAt(V(0, 0, 19)); step(40); tap('KeyE'); step(30)
assert(carrying.heldBy(stage.cub) === item, 'fixture pickup should use the real B interaction')
const safe = stage.cub.position.clone()
stage.cub.teleport(V(0, -2, 12)); step(60)
assert(stage.cub.position.distanceTo(safe) < 1, 'water fall should respawn locally')
assert(carrying.heldBy(stage.cub) === item && item.object.position.distanceTo(stage.cub.position) < 3, 'water respawn should bring the held item back')
play('mama'); stage.mama.placeAt(V(0, 0, 23)); step(40); tap('KeyR'); step(40)
assert(stage.coop.carrying, 'call should bring the acorn-holding Cub onto Mama')
stage.mama.teleport(V(0, -2, 12)); step(60)
assert(stage.coop.carrying && carrying.heldBy(stage.cub) === item, 'Mama splashing with Cub and acorn should recover both')
